using System.IO.Compression;
using System.Net.Http;
using System.Text.Json;
using System.Text.Json.Serialization;
using RoyalTerminal.Terminal.Theming;

namespace Wraithcairn;

/// <summary>One theme in the published catalog (website/static/themes/index.json).</summary>
public sealed class ThemeEntry
{
    public string Name { get; set; } = string.Empty;

    public string Slug { get; set; } = string.Empty;

    public bool Dark { get; set; } = true;

    public string Background { get; set; } = "#000000";

    public string Foreground { get; set; } = "#ffffff";

    public string? CursorColor { get; set; }

    public string? CursorText { get; set; }

    public string? SelectionBackground { get; set; }

    public string? SelectionForeground { get; set; }

    public string[] Palette { get; set; } = [];

    /// <summary>Found in a local theme folder (usable offline, no download needed).</summary>
    [JsonIgnore]
    public bool Installed { get; set; }

    /// <summary>Listed in the online catalog (can be downloaded).</summary>
    [JsonIgnore]
    public bool InCatalog { get; set; }

    /// <summary>Colors as normalized Ghostty keys (see <see cref="AppConfig.ThemeFromKeys"/>).</summary>
    public Dictionary<string, string> ToKeys()
    {
        Dictionary<string, string> keys = new(StringComparer.Ordinal)
        {
            ["background"] = Background,
            ["foreground"] = Foreground,
        };
        void Put(string key, string? value)
        {
            if (value is not null)
            {
                keys[key] = value;
            }
        }

        Put("cursor-color", CursorColor);
        Put("cursor-text", CursorText);
        Put("selection-background", SelectionBackground);
        Put("selection-foreground", SelectionForeground);
        for (int i = 0; i < Palette.Length && i < 16; i++)
        {
            keys[$"palette:{i}"] = $"{i}={Palette[i]}";
        }

        return keys;
    }

    public TerminalTheme ToTerminalTheme() => AppConfig.ThemeFromKeys(ToKeys());

    /// <summary>Ghostty theme-file text for this entry.</summary>
    public string ToGhosttyFile()
    {
        System.Text.StringBuilder sb = new();
        for (int i = 0; i < Palette.Length; i++)
        {
            sb.Append($"palette = {i}={Palette[i]}\n");
        }

        sb.Append($"background = {Background}\n");
        sb.Append($"foreground = {Foreground}\n");
        if (CursorColor is not null) sb.Append($"cursor-color = {CursorColor}\n");
        if (CursorText is not null) sb.Append($"cursor-text = {CursorText}\n");
        if (SelectionBackground is not null) sb.Append($"selection-background = {SelectionBackground}\n");
        if (SelectionForeground is not null) sb.Append($"selection-foreground = {SelectionForeground}\n");
        return sb.ToString();
    }

    /// <summary>Builds an entry from a local Ghostty theme file; null if it has no colors.</summary>
    public static ThemeEntry? FromFile(string name, string path)
    {
        Dictionary<string, string> keys;
        try
        {
            keys = AppConfig.ParseThemeFile(path);
        }
        catch
        {
            return null;
        }

        if (!keys.TryGetValue("background", out string? bg) || !keys.TryGetValue("foreground", out string? fg))
        {
            return null;
        }

        string[] palette = new string[16];
        TerminalTheme baseline = TerminalTheme.Dark;
        for (int i = 0; i < 16; i++)
        {
            palette[i] = keys.TryGetValue($"palette:{i}", out string? p) ? p[(p.IndexOf('=') + 1)..].Trim()
                : $"#{baseline.Palette[i] & 0xFFFFFF:x6}";
        }

        string? Get(string k) => keys.TryGetValue(k, out string? v) ? v : null;
        return new ThemeEntry
        {
            Name = name,
            Slug = ThemeCatalog.Slugify(name),
            Background = bg,
            Foreground = fg,
            CursorColor = Get("cursor-color"),
            CursorText = Get("cursor-text"),
            SelectionBackground = Get("selection-background"),
            SelectionForeground = Get("selection-foreground"),
            Palette = palette,
            Dark = AppConfig.TryParseColor(bg, out uint c) && Luminance(c) < 0.5,
            Installed = true,
        };
    }

    private static double Luminance(uint argb) =>
        ((0.2126 * ((argb >> 16) & 0xFF)) + (0.7152 * ((argb >> 8) & 0xFF)) + (0.0722 * (argb & 0xFF))) / 255.0;
}

/// <summary>
/// The theme catalog published with the docs site: Ghostty's built-in themes,
/// regenerated by scripts/sync-ghostty-themes.py into website/static/themes/.
///
///   {base}/index.json                  every theme's name and colors
///   {base}/ghostty/{slug}              one Ghostty-format theme file
///   {base}/wraithcairn-themes.zip      all of them (themes/{Name})
///
/// Downloads land in ~/.config/wraithcairn/themes/{Name}, which the normal
/// theme lookup already searches, so a downloaded theme works by name in
/// config.json and keeps working offline. WRAITHCAIRN_THEMES_URL overrides
/// the base URL (an http(s) URL or a local folder, e.g. for tests).
/// </summary>
public static class ThemeCatalog
{
    public const string DefaultBaseUrl = "https://ryandanthony.github.io/wraithcairn/themes/";

    private static readonly HttpClient Http = CreateClient();

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        PropertyNameCaseInsensitive = true,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
    };

    public static string BaseUrl
    {
        get
        {
            string? env = Environment.GetEnvironmentVariable("WRAITHCAIRN_THEMES_URL");
            if (string.IsNullOrWhiteSpace(env))
            {
                return DefaultBaseUrl;
            }

            return env.EndsWith('/') || env.EndsWith(Path.DirectorySeparatorChar) ? env : env + "/";
        }
    }

    /// <summary>Last fetched index.json, used when the site is unreachable.</summary>
    private static string CachePath => Path.Combine(AppConfig.ConfigDir, "theme-catalog.json");

    private sealed class CatalogDocument
    {
        public int Version { get; set; }

        public string? Source { get; set; }

        public List<ThemeEntry> Themes { get; set; } = [];
    }

    public sealed record CatalogResult(List<ThemeEntry> Themes, bool Online, string? Error, string? Source);

    private static HttpClient CreateClient()
    {
        HttpClient client = new() { Timeout = TimeSpan.FromSeconds(30) };
        client.DefaultRequestHeaders.UserAgent.ParseAdd($"wraithcairn/{AppInfo.Version.Split('+')[0]}");
        return client;
    }

    private static bool IsLocal(string baseUrl) =>
        !baseUrl.StartsWith("http://", StringComparison.OrdinalIgnoreCase)
        && !baseUrl.StartsWith("https://", StringComparison.OrdinalIgnoreCase);

    private static async Task<byte[]> GetBytesAsync(string relative, CancellationToken ct)
    {
        string baseUrl = BaseUrl;
        if (IsLocal(baseUrl))
        {
            string local = baseUrl.StartsWith("file://", StringComparison.OrdinalIgnoreCase)
                ? new Uri(baseUrl).LocalPath
                : baseUrl;
            return await File.ReadAllBytesAsync(Path.Combine(local, relative.Replace('/', Path.DirectorySeparatorChar)), ct);
        }

        return await Http.GetByteArrayAsync(new Uri(new Uri(baseUrl), relative), ct);
    }

    /// <summary>
    /// The online catalog merged with locally installed themes (installed
    /// ones not in the catalog, e.g. hand-made, are listed too). Falls back to
    /// the cached catalog, then to local themes only, when offline.
    /// </summary>
    public static async Task<CatalogResult> LoadAsync(CancellationToken ct = default)
    {
        List<ThemeEntry> online = [];
        bool isOnline = false;
        string? error = null;
        string? source = null;

        try
        {
            byte[] bytes = await GetBytesAsync("index.json", ct);
            CatalogDocument doc = JsonSerializer.Deserialize<CatalogDocument>(bytes, JsonOptions)
                ?? throw new InvalidDataException("empty catalog");
            online = doc.Themes;
            source = doc.Source;
            isOnline = true;
            try
            {
                Directory.CreateDirectory(AppConfig.ConfigDir);
                await File.WriteAllBytesAsync(CachePath, bytes, ct);
            }
            catch
            {
                // cache is best effort
            }
        }
        catch (Exception ex) when (ex is not OperationCanceledException || !ct.IsCancellationRequested)
        {
            error = ex.Message;
            try
            {
                if (File.Exists(CachePath))
                {
                    CatalogDocument? cached = JsonSerializer.Deserialize<CatalogDocument>(
                        await File.ReadAllBytesAsync(CachePath, ct), JsonOptions);
                    online = cached?.Themes ?? [];
                    source = cached?.Source;
                }
            }
            catch
            {
                // no usable cache
            }
        }

        Dictionary<string, ThemeEntry> byName = new(StringComparer.Ordinal);
        foreach (ThemeEntry entry in online.Where(e => IsSafeName(e.Name) && e.Palette.Length >= 16))
        {
            entry.InCatalog = true;
            byName.TryAdd(entry.Name, entry);
        }

        foreach ((string name, string path) in InstalledFiles())
        {
            if (byName.TryGetValue(name, out ThemeEntry? known))
            {
                known.Installed = true;
            }
            else if (ThemeEntry.FromFile(name, path) is { } local)
            {
                byName[name] = local;
            }
        }

        List<ThemeEntry> all = [.. byName.Values.OrderBy(e => e.Name, StringComparer.OrdinalIgnoreCase)];
        return new CatalogResult(all, isOnline, error, source);
    }

    /// <summary>Theme files in the local theme folders, first folder wins per name.</summary>
    public static IEnumerable<(string Name, string Path)> InstalledFiles()
    {
        HashSet<string> seen = new(StringComparer.Ordinal);
        foreach (string dir in AppConfig.ThemeDirs)
        {
            string[] files;
            try
            {
                files = Directory.Exists(dir) ? Directory.GetFiles(dir) : [];
            }
            catch
            {
                continue;
            }

            foreach (string file in files)
            {
                string name = Path.GetFileName(file);
                if (!name.StartsWith('.') && !name.EndsWith(".tmp", StringComparison.Ordinal) && seen.Add(name))
                {
                    yield return (name, file);
                }
            }
        }
    }

    public static bool IsInstalled(string name) => AppConfig.FindThemeFile(name) is not null;

    /// <summary>Downloads one theme into the user theme folder. Returns the file path.</summary>
    public static async Task<string> DownloadAsync(ThemeEntry entry, CancellationToken ct = default)
    {
        if (!IsSafeName(entry.Name) || !IsSafeSlug(entry.Slug))
        {
            throw new InvalidDataException($"unsafe theme name: {entry.Name}");
        }

        string text;
        try
        {
            text = System.Text.Encoding.UTF8.GetString(await GetBytesAsync($"ghostty/{entry.Slug}", ct));
        }
        catch when (entry.Palette.Length >= 16)
        {
            // The catalog already carries every color; write it ourselves.
            text = entry.ToGhosttyFile();
        }

        string path = WriteTheme(entry.Name, text);
        entry.Installed = true;
        return path;
    }

    /// <summary>
    /// Downloads every catalog theme (one zip) into the user theme folder.
    /// Reports (done, total). Returns the number of themes written.
    /// </summary>
    public static async Task<int> DownloadAllAsync(IProgress<(int Done, int Total)>? progress = null, CancellationToken ct = default)
    {
        progress?.Report((0, 0));
        byte[] zip = await GetBytesAsync("wraithcairn-themes.zip", ct);
        using MemoryStream stream = new(zip);
        using ZipArchive archive = new(stream, ZipArchiveMode.Read);
        List<ZipArchiveEntry> entries = [.. archive.Entries.Where(e => e.FullName.StartsWith("themes/", StringComparison.Ordinal) && e.Name.Length > 0)];
        int written = 0;
        for (int i = 0; i < entries.Count; i++)
        {
            ct.ThrowIfCancellationRequested();
            ZipArchiveEntry entry = entries[i];
            string name = entry.FullName["themes/".Length..];
            if (!IsSafeName(name) || entry.Length > 64 * 1024)
            {
                continue;
            }

            using StreamReader reader = new(entry.Open());
            WriteTheme(name, await reader.ReadToEndAsync(ct));
            written++;
            if (i % 25 == 0 || i == entries.Count - 1)
            {
                progress?.Report((i + 1, entries.Count));
            }
        }

        return written;
    }

    private static string WriteTheme(string name, string text)
    {
        // Must at least look like a theme (guards against an HTML error page).
        if (!text.Contains("background", StringComparison.Ordinal) || !text.Contains("palette", StringComparison.Ordinal))
        {
            throw new InvalidDataException($"not a theme file: {name}");
        }

        Directory.CreateDirectory(AppConfig.UserThemesDir);
        string path = Path.Combine(AppConfig.UserThemesDir, name);
        string tmp = path + ".tmp";
        File.WriteAllText(tmp, text);
        File.Move(tmp, path, overwrite: true);
        return path;
    }

    /// <summary>A theme name that is safe as a file name on every OS.</summary>
    public static bool IsSafeName(string name) =>
        !string.IsNullOrWhiteSpace(name)
        && name.Length <= 128
        && name is not ("." or "..")
        && !name.StartsWith('.')
        && name.IndexOfAny(['/', '\\', ':', '*', '?', '"', '<', '>', '|', '\0']) < 0
        && !name.Any(char.IsControl);

    private static bool IsSafeSlug(string slug) =>
        slug.Length > 0 && slug.All(c => c is (>= 'a' and <= 'z') or (>= '0' and <= '9') or '-');

    /// <summary>Same rule as scripts/sync-ghostty-themes.py.</summary>
    public static string Slugify(string name)
    {
        System.Text.StringBuilder sb = new();
        bool dash = false;
        foreach (char c in name.ToLowerInvariant().Replace("+", "-plus", StringComparison.Ordinal))
        {
            if (c is (>= 'a' and <= 'z') or (>= '0' and <= '9'))
            {
                sb.Append(c);
                dash = false;
            }
            else if (!dash)
            {
                sb.Append('-');
                dash = true;
            }
        }

        return sb.ToString().Trim('-');
    }
}
